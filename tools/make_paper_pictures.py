"""Pictures for the three papers, drawn from the mathematics itself (no data files needed).

  papers/hook-length        a skew Young diagram lambda/mu with the hook length of every cell,
                            hooks measured in lambda (the setting of the Naruse formula)
  papers/diagonal-derivative  a semistandard skew tableau of the same shape, main diagonal shaded
  papers/lyndon-words       the Lyndon words over {1, 2} up to length 7, generated by Duval's algorithm

Like the project pictures, each PNG is black with the drawing in its transparency; the site
paints it in the theme's accent colour. Run:  python tools/make_paper_pictures.py
"""
import os

from PIL import Image, ImageDraw, ImageFont

SITE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT = r"C:\Windows\Fonts\consola.ttf"

LAMBDA = (7, 6, 4, 4, 2)   # outer shape
MU = (3, 1, 1)             # removed inner shape


def save(img, slug, name):
    """img: an 'L' image whose values are the opacity. Saved as black with that transparency."""
    out = Image.new("RGBA", img.size, (0, 0, 0, 0))
    out.putalpha(img)
    path = os.path.join(SITE, "papers", slug, name + ".png")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    out.save(path, optimize=True)
    print(f"papers/{slug}/{name}.png {img.size}")


def cells(lam, mu):
    mu = list(mu) + [0] * (len(lam) - len(mu))
    return [(i, j) for i in range(len(lam)) for j in range(mu[i], lam[i])]


def hook(lam, i, j):
    """Hook length of cell (i, j) in the straight shape lam."""
    arm = lam[i] - j - 1
    leg = sum(1 for r in range(i + 1, len(lam)) if lam[r] > j)
    return arm + leg + 1


def semistandard(lam, mu):
    """A semistandard filling of lam/mu: each cell gets 1 + the number of cells above it in its column."""
    cs = set(cells(lam, mu))
    t = {(i, j): 1 + sum(1 for r in range(i) if (r, j) in cs) for (i, j) in cs}
    for (i, j), v in t.items():  # check: rows weakly increase, columns strictly increase
        assert (i, j + 1) not in t or t[(i, j + 1)] >= v
        assert (i + 1, j) not in t or t[(i + 1, j)] > v
    return t


def draw_diagram(size, labels, shade=(), box=None, right=0.62):
    """Young diagram in English notation, placed towards the right so the page title can sit at the left."""
    W, H = size
    rows = max(i for i, _ in labels) + 1
    cols = max(j for _, j in labels) + 1
    box = box or int(min(H * 0.9 / rows, W * 0.9 / cols))
    x0 = int(W * right - cols * box / 2)
    y0 = int((H - rows * box) / 2)
    img = Image.new("L", size, 0)
    d = ImageDraw.Draw(img)
    font = ImageFont.truetype(FONT, int(box * 0.5))
    lw = max(2, box // 28)
    for (i, j), text in labels.items():
        x, y = x0 + j * box, y0 + i * box
        if (i, j) in shade:
            d.rectangle([x, y, x + box, y + box], fill=70)
        d.rectangle([x, y, x + box, y + box], outline=255, width=lw)
        d.text((x + box / 2, y + box / 2), str(text), fill=255, font=font, anchor="mm")
    return img


def lyndon_words(alphabet, n):
    """Duval's algorithm: all Lyndon words of length <= n, in lexicographic order."""
    k = len(alphabet)
    w = [-1]
    out = []
    while w:
        w[-1] += 1
        out.append("".join(alphabet[c] for c in w))
        m = len(w)
        while len(w) < n:
            w.append(w[len(w) - m])
        while w and w[-1] == k - 1:
            w.pop()
    return out


def draw_words(size, words, right=0.6):
    W, H = size
    img = Image.new("L", size, 0)
    d = ImageDraw.Draw(img)
    font = ImageFont.truetype(FONT, int(H * 0.075))
    cols = 4
    per = -(-len(words) // cols)
    colw, rowh = W * 0.24, H * 0.85 / per
    x0 = W * right - cols * colw / 2
    for n, w in enumerate(words):
        c, r = divmod(n, per)
        d.text((x0 + c * colw, H * 0.06 + r * rowh), w, fill=255, font=font)
    return img


if __name__ == "__main__":
    lam, mu = LAMBDA, MU
    hooks = {(i, j): hook(lam, i, j) for (i, j) in cells(lam, mu)}
    tab = semistandard(lam, mu)
    diagonal = {(i, j) for (i, j) in tab if i == j}
    for name, size in (("banner", (760, 560)), ("thumb", (240, 240))):
        save(draw_diagram(size, hooks, right=0.5), "hook-length", name)
        save(draw_diagram(size, tab, shade=diagonal, right=0.5), "diagonal-derivative", name)
    words = lyndon_words("12", 7)
    print(len(words), "Lyndon words:", " ".join(words))
    save(draw_words((1000, 600), words, right=0.5), "lyndon-words", "banner")
    save(draw_words((240, 240), words[:12], right=0.5), "lyndon-words", "thumb")
